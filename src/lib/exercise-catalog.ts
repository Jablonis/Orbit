/** The muscle group Orbit counts this exercise under, or null for cardio. */
export function catalogMuscle(exercise: CatalogExercise): MuscleGroup | null {
  return TARGET_TO_MUSCLE[exercise.target.toLowerCase()] ?? null;
}


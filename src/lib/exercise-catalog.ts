const byId = new Map(CATALOG.map((exercise) => [exercise.id, exercise]));

export function getCatalogExercise(id: string): CatalogExercise | null {
  return byId.get(id) ?? null;
}

/** True for an id this module owns, so a caller can route a lookup. */
export function isCatalogId(id: string) {
  return id.startsWith("cat-");
}


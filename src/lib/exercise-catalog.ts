/**
 * The catalogue entry behind any exercise id Orbit can log, curated or not, or
 * null when there is nothing honest to show.
 */
export function catalogEntryFor(exerciseId: string): CatalogExercise | null {
  if (isCatalogId(exerciseId)) return getCatalogExercise(exerciseId);
  const linked = CURATED_TO_CATALOG[exerciseId];
  return linked ? getCatalogExercise(linked) : null;
}

/** Every body part present, most exercises first — the filter row's order. */
export const CATALOG_BODY_PARTS: string[] = [
  ...new Map(
    CATALOG.map((exercise) => [exercise.bodyPart, exercise.bodyPart]),
  ).keys(),
].sort((a, b) => count(b) - count(a) || (a < b ? -1 : 1));

function count(bodyPart: string) {
  return CATALOG.filter((exercise) => exercise.bodyPart === bodyPart).length;
}

/**
 * The equipment worth offering for a list that is already filtered, most
 * common first. Deriving it from the filtered list rather than from the whole
 * catalogue keeps the row short and means every chip on screen has results
 * behind it.
 */
export function equipmentInList(list: CatalogExercise[]): string[] {
  const counts = new Map<string, number>();
  for (const exercise of list) {
    if (!exercise.equipment) continue;
    counts.set(exercise.equipment, (counts.get(exercise.equipment) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .map(([equipment]) => equipment);
}

/** Accents off, case off — the search box is typed into on a phone. */
function normalize(value: string) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
}

export type CatalogQuery = {
  bodyPart?: string;
  equipment?: string;
  /** Only what this kit can do. Undefined means show everything. */
  kit?: FitnessEquipment[];
  muscle?: MuscleGroup;
  search?: string;
};

/**
 * The catalogue, filtered.
 *
 * Every word typed has to match somewhere in the name, so "cable row" narrows
 * rather than widens — the opposite behaviour turns 1 324 exercises into a
 * list that always has everything in it. A name that starts with the search
 * sorts first, because "row" should reach "row" before "barbell bent-over row".
 */
export function searchCatalog(query: CatalogQuery): CatalogExercise[] {
  const terms = normalize(query.search ?? "")
    .split(/\s+/)
    .filter(Boolean);
  const kit = query.kit ? new Set(query.kit) : null;

  const matched = CATALOG.filter((exercise) => {
    if (query.bodyPart && exercise.bodyPart !== query.bodyPart) return false;
    if (query.equipment && exercise.equipment !== query.equipment) return false;
    if (query.muscle && catalogMuscle(exercise) !== query.muscle) return false;
    if (kit && !catalogKit(exercise).some((item) => kit.has(item))) return false;
    if (terms.length === 0) return true;
    const name = normalize(exercise.name);
    return terms.every((term) => name.includes(term));
  });

  if (terms.length === 0) return matched;

  const first = terms[0];
  return matched.sort((a, b) => {
    const rank =
      Number(normalize(b.name).startsWith(first)) -
      Number(normalize(a.name).startsWith(first));
    return rank || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  });
}

/**
 * Where the pictures live, or nothing.
 *
 * The animations are © Gym visual and this repository does not carry them, so
 * the default is no media at all and the catalogue reads perfectly well without
 * it: a name, the muscle, the kit and the steps. A deployment that has settled
 * its own terms with Gym visual points this at its copy and the pictures appear.
 */
export function catalogMediaBase(): string {
  const base = process.env.NEXT_PUBLIC_EXERCISE_MEDIA_BASE ?? "";
  return base ? base.replace(/\/+$/, "") : "";
}

export function catalogImageSrc(exercise: CatalogExercise): string {
  const base = catalogMediaBase();
  return base && exercise.image ? `${base}/img/${exercise.image}` : "";
}

export function catalogGifSrc(exercise: CatalogExercise): string {
  const base = catalogMediaBase();
  return base && exercise.gif ? `${base}/gif/${exercise.gif}` : "";
}

/**
 * A catalogue entry flattened into the handful of strings a screen shows.
 *
 * The reason this type exists is the client boundary. The session log is a
 * client component, and anything it imports goes to the phone — so it is
 * handed finished sentences instead of the module that could produce them.
 */
export type ExerciseGuide = {
  attribution: string;
  /** Body part, muscle group, equipment, kit — the chips above the steps. */
  facts: string[];
  /** The animation if a deployment has licensed one, else the still, else "". */
  mediaSrc: string;
  name: string;
  secondaryMuscles: string[];
  steps: string[];
};

export function buildExerciseGuide(entry: CatalogExercise): ExerciseGuide {
  const muscle = catalogMuscle(entry);
  return {
    attribution: CATALOG_ATTRIBUTION,
    // Deduplicated: "chest" is both the body part and the muscle group for
    // half the chest exercises, and a row that says chest twice reads as a bug.
    facts: [
      ...new Set(
        [
          entry.bodyPart,
          muscle ?? "cardio",
          entry.equipment,
          catalogKit(entry)
            .map((item) => fitnessEquipmentLabels[item])
            .join(" or "),
        ]
          .filter(Boolean)
          .map((fact) => fact.toLowerCase()),
      ),
    ],
    mediaSrc: catalogGifSrc(entry) || catalogImageSrc(entry),
    name: entry.name,
    secondaryMuscles: entry.secondaryMuscles,
    steps: entry.steps,
  };
}

/** The guide for any exercise id Orbit can log, or null when there is none. */
export function guideFor(exerciseId: string): ExerciseGuide | null {
  const entry = catalogEntryFor(exerciseId);
  return entry ? buildExerciseGuide(entry) : null;
}
